if(!html.includes('double-advanced-classroom.framedegret8.chatgpt.site')) throw new Error('Pages must redirect to the authenticated application.');
await writeFile(new URL('index.html',output),html);
await writeFile(new URL('404.html',output),html);
await writeFile(new URL('CNAME',output),'donteventry.me\n');
